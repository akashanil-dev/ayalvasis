from odoo import api, fields, models, Command, _
from odoo.exceptions import AccessError, UserError, ValidationError
from .common import require_admin, require_finance


class Discount(models.Model):
    _name = 'ayal.subscription.discount'
    _description = 'Recurring discount rule'
    _order = 'priority,id'
    name = fields.Char(required=True)
    active = fields.Boolean(default=True)
    company_id = fields.Many2one('res.company', required=True, default=lambda s: s.env.company)
    currency_id = fields.Many2one(related='company_id.currency_id')
    priority = fields.Integer(default=10)
    kind = fields.Selection([('percent', 'Percentage'), ('fixed', 'Fixed amount')], default='percent', required=True)
    value = fields.Float(required=True)
    date_from = fields.Date(required=True, default=fields.Date.context_today)
    date_until = fields.Date(required=True)
    min_amount = fields.Monetary(default=0)
    min_quantity = fields.Integer(default=1)
    usage_limit = fields.Integer(default=0, help='Zero means unlimited. Draft invoices reserve a use.')
    product_ids = fields.Many2many('product.product')
    subscription_ids = fields.Many2many('ayal.subscription')
    _bounds = models.Constraint("CHECK(value >= 0 AND (kind != 'percent' OR value <= 100) AND min_amount >= 0 AND min_quantity > 0 AND usage_limit >= 0 AND date_until >= date_from)", 'Invalid discount value, threshold, limit or dates.')

    @api.model_create_multi
    def create(self, vals):
        require_admin(self.env)
        return super().create(vals)

    def write(self, vals):
        require_admin(self.env)
        return super().write(vals)

    def unlink(self):
        require_admin(self.env)
        return super().unlink()


class BillingPeriod(models.Model):
    _name = 'ayal.billing.period'
    _description = 'Recurring billing period'
    _check_company_auto = True
    _order = 'start_date desc,id desc'
    subscription_id = fields.Many2one('ayal.subscription', required=True, ondelete='restrict', index=True, check_company=True)
    company_id = fields.Many2one(related='subscription_id.company_id', store=True, index=True)
    currency_id = fields.Many2one(related='subscription_id.currency_id')
    start_date = fields.Date(required=True, index=True)
    end_date = fields.Date(required=True)
    proration = fields.Float(required=True)
    invoice_id = fields.Many2one('account.move', readonly=True, check_company=True, ondelete='restrict')
    discount_id = fields.Many2one('ayal.subscription.discount', readonly=True, ondelete='restrict')
    reservation = fields.Selection([('none', 'None'), ('reserved', 'Reserved'), ('consumed', 'Consumed'), ('released', 'Released')], default='none', required=True)
    discount_amount = fields.Monetary(readonly=True)
    _period_unique = models.Constraint('UNIQUE(subscription_id,start_date)', 'This period has already been billed.')
    _period_dates = models.Constraint('CHECK(end_date > start_date AND proration > 0 AND proration <= 1)', 'Invalid service period.')

    @api.model_create_multi
    def create(self, vals):
        if not self.env.su:
            raise AccessError(_('Billing periods are generated by the billing engine.'))
        return super().create(vals)

    def write(self, vals):
        if not self.env.su:
            raise AccessError(_('Billing periods cannot be edited manually.'))
        return super().write(vals)

    def unlink(self):
        raise AccessError(_('Billing periods are permanent audit records.'))

    @api.model
    def _generate(self, subscription, start, end, ratio):
        existing = self.sudo().search([('subscription_id', '=', subscription.id), ('start_date', '=', start)], limit=1)
        if existing:
            return existing
        env = self.sudo().with_company(subscription.company_id).env
        company = subscription.company_id
        journal = env['account.journal'].search([('type', '=', 'sale'), ('company_id', '=', company.id)], limit=1)
        if not journal:
            raise UserError(_('Configure a sales journal and chart of accounts before billing.'))
        lines = subscription.sudo().line_ids
        # Taxes may include price-included components: eligibility uses the untaxed amount.
        bases = {l.id: l.tax_ids.compute_all(l.price_unit * ratio, currency=subscription.currency_id,
                  quantity=l.quantity, product=l.product_id, partner=subscription.partner_id)['total_excluded'] for l in lines}
        selected, eligible, amount = env['ayal.subscription.discount'], lines.browse(), 0.0
        rules = env['ayal.subscription.discount'].search([('company_id', '=', company.id), ('date_from', '<=', start), ('date_until', '>=', start)])
        for rule in rules:
            env.cr.execute('SELECT id FROM ayal_subscription_discount WHERE id=%s FOR UPDATE', [rule.id])
            # Updating the locked row forces a serialization retry for a stale
            # REPEATABLE READ snapshot before a second worker can claim the last use.
            env.cr.execute('UPDATE ayal_subscription_discount SET write_date=clock_timestamp() WHERE id=%s', [rule.id])
            rule.invalidate_recordset()
            if not rule.active or (rule.subscription_ids and subscription.id not in rule.subscription_ids.ids):
                continue
            candidates = lines.filtered(lambda l: not rule.product_ids or l.product_id in rule.product_ids)
            base = sum(bases[l.id] for l in candidates)
            used = env['ayal.billing.period'].search_count([('discount_id', '=', rule.id), ('reservation', 'in', ['reserved', 'consumed'])])
            if base <= 0 or base < rule.min_amount or sum(candidates.mapped('quantity')) < rule.min_quantity or (rule.usage_limit and used >= rule.usage_limit):
                continue
            selected, eligible = rule, candidates
            amount = subscription.currency_id.round(min(base, base * rule.value / 100 if rule.kind == 'percent' else rule.value))
            break
        period = env['ayal.billing.period'].create({'subscription_id': subscription.id, 'start_date': start, 'end_date': end,
                  'proration': ratio, 'discount_id': selected.id, 'reservation': 'reserved' if selected else 'none', 'discount_amount': amount})
        base = sum(bases[l.id] for l in eligible)
        invoice_lines = []
        allocation, remaining = {}, amount
        for index, line in enumerate(eligible):
            share = remaining if index == len(eligible) - 1 else subscription.currency_id.round(amount * bases[line.id] / base)
            share = min(share, bases[line.id], remaining)
            allocation[line.id] = share
            remaining -= share
        for line in lines:
            # A single proportional rate allocates fixed discounts across eligible untaxed lines.
            discount = allocation.get(line.id, 0) / bases[line.id] * 100 if bases[line.id] else 0
            accounts = line.product_id.product_tmpl_id.get_product_accounts()
            income = accounts['income'] or journal.default_account_id
            if not income:
                raise UserError(_('Configure an income account for %s.', line.product_id.display_name))
            invoice_lines.append(Command.create({'product_id': line.product_id.id,
                'name': '%s — %s to %s (exclusive)' % (line.name, start, end),
                'account_id': income.id, 'quantity': line.quantity, 'price_unit': line.price_unit * ratio,
                'discount': discount, 'tax_ids': [Command.set(line.tax_ids.ids)]}))
        invoice = env['account.move'].create({'move_type': 'out_invoice', 'partner_id': subscription.partner_id.id,
                   'company_id': company.id, 'journal_id': journal.id, 'invoice_date': start,
                   'invoice_payment_term_id': subscription.accepted_payment_term_id.id,
                   'invoice_origin': subscription.name, 'ref': '%s / %s' % (subscription.name, start),
                   'ayal_period_id': period.id, 'invoice_line_ids': invoice_lines})
        period.write({'invoice_id': invoice.id})
        if subscription.snapshot.get('auto_post'):
            invoice.action_post()
        subscription._event('invoice_generated', '%s / %s' % (invoice.id, start))
        return period

    def action_open_invoice(self):
        self.ensure_one()
        self.check_access('read')
        return {'type': 'ir.actions.act_window', 'res_model': 'account.move', 'res_id': self.invoice_id.id, 'view_mode': 'form'}

    def action_reissue(self):
        require_finance(self.env)
        self.ensure_one()
        self.check_access('read')
        self.subscription_id._lock()
        old = self.invoice_id
        if old.state != 'cancel' or old.posted_before:
            raise UserError(_('Only a cancelled, never-posted invoice can be reissued. Use a credit note for posted invoices.'))
        if self.discount_id:
            self.env.cr.execute('SELECT id FROM ayal_subscription_discount WHERE id=%s FOR UPDATE', [self.discount_id.id])
            self.env.cr.execute('UPDATE ayal_subscription_discount SET write_date=clock_timestamp() WHERE id=%s', [self.discount_id.id])
            count = self.sudo().search_count([('discount_id', '=', self.discount_id.id), ('reservation', 'in', ['reserved', 'consumed'])])
            if self.discount_id.usage_limit and count >= self.discount_id.usage_limit:
                raise UserError(_('The discount usage limit is exhausted.'))
        replacement = old.sudo().copy({'ayal_period_id': self.id})
        self.sudo().write({'invoice_id': replacement.id, 'reservation': 'reserved' if self.discount_id else 'none'})
        self.subscription_id._event('invoice_reissued', str(replacement.id))
        return self.action_open_invoice()
